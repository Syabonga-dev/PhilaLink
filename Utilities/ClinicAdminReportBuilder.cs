        private static void Csv(
            StringBuilder builder,
            params object?[] values
        )
        {
            builder.AppendLine(
                string.Join(
                    ",",
                    values.Select(
                        CsvValue
                    )
                )
            );
        }

        private static string CsvValue(
            object? value
        )
        {
            var text =
                ValueText(
                    value
                )
                .Replace(
                    "\"",
                    "\"\""
                );

            return
                $"\"{text}\"";
        }

        private static string ValueText(
            object? value
        )
        {
            return value switch
            {
                null =>
                    "",

                DateTime date =>
                    DateTimeText(
                        date
                    ),

                bool boolean =>
                    boolean
                        ? "Yes"
                        : "No",

                IFormattable valueFormatter =>
                    valueFormatter.ToString(
                        null,
                        CultureInfo.InvariantCulture
                    ) ??
                    "",

                _ =>
                    value.ToString() ??
                    ""
            };
        }

        private static string Xml(
            string value
        )
        {
            return
                SecurityElement.Escape(
                    value
                ) ??
                "";
        }

        private static string EscapePdf(
            string value
        )
        {
            return value
                .Replace(
                    "\\",
                    "\\\\"
                )
                .Replace(
                    "(",
                    "\\("
                )
                .Replace(
                    ")",
                    "\\)"
                );
        }

        private static string Ascii(
            string value
        )
        {
            var builder =
                new StringBuilder(
                    value.Length
                );

            foreach (
                var character in
                    value
            )
            {
                builder.Append(
                    character <=
                    127
                        ? character
                        : '?'
                );
            }

            return builder.ToString();
        }

        private static string DateText(
            DateTime value
        )
        {
            return value.ToString(
                "yyyy-MM-dd",
                CultureInfo.InvariantCulture
            );
        }

        private static string DateTimeText(
            DateTime value
        )
        {
            return value.ToString(
                "yyyy-MM-dd HH:mm",
                CultureInfo.InvariantCulture
            );
        }

