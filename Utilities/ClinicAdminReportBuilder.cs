        public static byte[] BuildPdf(
            ClinicAdminReportDataDto report
        )
        {
            var sourceLines =
                BuildPdfLines(
                    report
                );

            var lines =
                new List<string>();

            foreach (
                var line in
                    sourceLines
            )
            {
                lines.AddRange(
                    Wrap(
                        line,
                        90
                    )
                );
            }

            var pages =
                lines
                    .Chunk(
                        48
                    )
                    .Select(
                        page =>
                            page.ToList()
                    )
                    .ToList();

            if (
                pages.Count ==
                0
            )
            {
                pages.Add(
                    new List<string>
                    {
                        "PhilaLink Clinic Report"
                    }
                );
            }

            return SimplePdf(
                pages
            );
        }

