        public static byte[] BuildXlsx(
            ClinicAdminReportDataDto report
        )
        {
            var sheets =
                new List<SheetDefinition>
                {
                    new(
                        "Summary",
                        SummaryRows(
                            report
                        )
                    ),

                    new(
                        "Appointments",
                        AppointmentRows(
                            report
                        )
                    ),

                    new(
                        "Collections",
                        CollectionRows(
                            report
                        )
                    ),

                    new(
                        "Inventory",
                        InventoryRows(
                            report
                        )
                    ),

                    new(
                        "Staff",
                        StaffRows(
                            report
                        )
                    ),

                    new(
                        "New Patients",
                        PatientRows(
                            report
                        )
                    )
                };

            using var memory =
                new MemoryStream();

            using (
                var archive =
                    new ZipArchive(
                        memory,
                        ZipArchiveMode.Create,
                        true
                    )
            )
            {
                WriteEntry(
                    archive,
                    "[Content_Types].xml",
                    ContentTypes(
                        sheets.Count
                    )
                );

                WriteEntry(
                    archive,
                    "_rels/.rels",
                    """
                    <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
                    <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
                      <Relationship Id="rId1"
                        Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument"
                        Target="xl/workbook.xml"/>
                    </Relationships>
                    """
                );

                WriteEntry(
                    archive,
                    "xl/workbook.xml",
                    Workbook(
                        sheets
                    )
                );

                WriteEntry(
                    archive,
                    "xl/_rels/workbook.xml.rels",
                    WorkbookRelationships(
                        sheets.Count
                    )
                );

                WriteEntry(
                    archive,
                    "xl/styles.xml",
                    Styles()
                );

                for (
                    var index = 0;
                    index <
                        sheets.Count;
                    index++
                )
                {
                    WriteEntry(
                        archive,
                        $"xl/worksheets/sheet{index + 1}.xml",
                        Worksheet(
                            sheets[index]
                                .Rows
                        )
                    );
                }
            }

            return memory.ToArray();
        }

