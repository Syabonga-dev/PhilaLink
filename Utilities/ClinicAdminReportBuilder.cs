        private static string Worksheet(
            IReadOnlyList<List<object?>>
                rows
        )
        {
            var builder =
                new StringBuilder();

            builder.Append(
                """
                <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
                <worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
                  <sheetData>
                """
            );

            for (
                var rowIndex = 0;
                rowIndex <
                    rows.Count;
                rowIndex++
            )
            {
                var excelRow =
                    rowIndex + 1;

                builder.Append(
                    $"<row r=\"{excelRow}\">"
                );

                for (
                    var columnIndex = 0;
                    columnIndex <
                        rows[rowIndex].Count;
                    columnIndex++
                )
                {
                    Cell(
                        builder,
                        $"{Column(columnIndex + 1)}{excelRow}",
                        rows[rowIndex][columnIndex]
                    );
                }

                builder.Append(
                    "</row>"
                );
            }

            builder.Append(
                """
                  </sheetData>
                </worksheet>
                """
            );

            return builder.ToString();
        }

        private static void Cell(
            StringBuilder builder,
            string reference,
            object? value
        )
        {
            if (
                value == null
            )
            {
                builder.Append(
                    $"<c r=\"{reference}\"/>"
                );

                return;
            }

            if (
                value is byte ||
                value is short ||
                value is int ||
                value is long ||
                value is float ||
                value is double ||
                value is decimal
            )
            {
                builder.Append(
                    $"<c r=\"{reference}\"><v>{Convert.ToString(value, CultureInfo.InvariantCulture)}</v></c>"
                );

                return;
            }

            builder.Append(
                $"<c r=\"{reference}\" t=\"inlineStr\"><is><t>{Xml(ValueText(value))}</t></is></c>"
            );
        }

        private static string Column(
            int index
        )
        {
            var value =
                string.Empty;

            while (
                index > 0
            )
            {
                index--;

                value =
                    (char)(
                        'A' +
                        index %
                        26
                    ) +
                    value;

                index /=
                    26;
            }

            return value;
        }

        private static void WriteEntry(
            ZipArchive archive,
            string name,
            string content
        )
        {
            var entry =
                archive.CreateEntry(
                    name,
                    CompressionLevel.Fastest
                );

            using var stream =
                entry.Open();

            using var writer =
                new StreamWriter(
                    stream,
                    new UTF8Encoding(
                        false
                    )
                );

            writer.Write(
                content
            );
        }

