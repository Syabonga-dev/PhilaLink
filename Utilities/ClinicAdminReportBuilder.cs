        private static byte[] SimplePdf(
            IReadOnlyList<List<string>>
                pages
        )
        {
            using var stream =
                new MemoryStream();

            var offsets =
                new List<long>
                {
                    0
                };

            void WriteAscii(
                string value
            )
            {
                var bytes =
                    Encoding.ASCII.GetBytes(
                        value
                    );

                stream.Write(
                    bytes,
                    0,
                    bytes.Length
                );
            }

            WriteAscii(
                "%PDF-1.4\n"
            );

            var objectCount =
                3 +
                pages.Count *
                2;

            var pageIds =
                Enumerable
                    .Range(
                        0,
                        pages.Count
                    )
                    .Select(
                        index =>
                            4 +
                            index *
                            2
                    )
                    .ToList();

            var objects =
                new Dictionary<int, string>
                {
                    [1] =
                        "<< /Type /Catalog /Pages 2 0 R >>",

                    [2] =
                        $"<< /Type /Pages /Kids [{string.Join(" ", pageIds.Select(id => $"{id} 0 R"))}] /Count {pages.Count} >>",

                    [3] =
                        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
                };

            for (
                var index = 0;
                index <
                    pages.Count;
                index++
            )
            {
                var pageId =
                    4 +
                    index *
                    2;

                var contentId =
                    pageId + 1;

                var content =
                    PdfPage(
                        pages[index]
                    );

                objects[pageId] =
                    $"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents {contentId} 0 R >>";

                objects[contentId] =
                    $"<< /Length {Encoding.ASCII.GetByteCount(content)} >>\nstream\n{content}\nendstream";
            }

            for (
                var id = 1;
                id <=
                    objectCount;
                id++
            )
            {
                offsets.Add(
                    stream.Position
                );

                WriteAscii(
                    $"{id} 0 obj\n{objects[id]}\nendobj\n"
                );
            }

            var xref =
                stream.Position;

            WriteAscii(
                $"xref\n0 {objectCount + 1}\n"
            );

            WriteAscii(
                "0000000000 65535 f \n"
            );

            for (
                var id = 1;
                id <=
                    objectCount;
                id++
            )
            {
                WriteAscii(
                    $"{offsets[id]:D10} 00000 n \n"
                );
            }

            WriteAscii(
                $"trailer\n<< /Size {objectCount + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF"
            );

            return stream.ToArray();
        }

        private static string PdfPage(
            IReadOnlyList<string>
                lines
        )
        {
            var builder =
                new StringBuilder();

            builder.AppendLine(
                "BT"
            );

            builder.AppendLine(
                "/F1 9 Tf"
            );

            builder.AppendLine(
                "40 750 Td"
            );

            builder.AppendLine(
                "14 TL"
            );

            foreach (
                var line in
                    lines
            )
            {
                builder.Append(
                    "("
                );

                builder.Append(
                    EscapePdf(
                        Ascii(
                            line
                        )
                    )
                );

                builder.AppendLine(
                    ") Tj"
                );

                builder.AppendLine(
                    "T*"
                );
            }

            builder.Append(
                "ET"
            );

            return builder.ToString();
        }

        private static IEnumerable<string>
            Wrap(
                string text,
                int maximum
            )
        {
            if (
                string.IsNullOrEmpty(
                    text
                )
            )
            {
                yield return "";
                yield break;
            }

            var remaining =
                text.Trim();

            while (
                remaining.Length >
                    maximum
            )
            {
                var split =
                    remaining.LastIndexOf(
                        ' ',
                        maximum
                    );

                if (
                    split <= 0
                )
                {
                    split =
                        maximum;
                }

                yield return
                    remaining[
                        ..split
                    ];

                remaining =
                    remaining[
                        split..
                    ]
                    .Trim();
            }

            yield return
                remaining;
        }

