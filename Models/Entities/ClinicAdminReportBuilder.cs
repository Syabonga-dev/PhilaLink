        public static byte[] BuildPdf(
            ClinicAdminReportDataDto report
        )
        {
            var lines =
                BuildPdfLines(
                    report
                );

            var wrapped =
                new List<string>();

            foreach (
                var line in lines
            )
            {
                wrapped.AddRange(
                    WrapText(
                        line,
                        92
                    )
                );
            }

            const int linesPerPage =
                48;

            var pages =
                wrapped
                    .Chunk(
                        linesPerPage
                    )
                    .Select(
                        page =>
                            page.ToList()
                    )
                    .ToList();

            if (
                pages.Count == 0
            )
            {
                pages.Add(
                    new List<string>
                    {
                        "PhilaLink Clinic Report"
                    }
                );
            }

            return BuildSimplePdf(
                pages
            );
        }

