                    $"{item.MedicationName} {item.Strength} | {item.QuantityOnHand} {item.Unit} | Reorder {item.ReorderLevel} | {item.Status}"
                );
            }

            lines.Add("");
            lines.Add(
                "STAFF"
            );

            foreach (
                var item in
                    report.Staff
            )
            {
                lines.Add(
                    $"{item.FullName} | {item.Role} | {(item.IsActive ? "Active" : "Inactive")}"
                );
            }

            lines.Add("");
            lines.Add(
                "NEW PATIENTS"
            );

            foreach (
                var item in
                    report.NewPatients
            )
            {
                lines.Add(
                    $"{item.FullName} | {item.PatientNumber} | {FormatDate(item.CreatedAt)}"
                );
            }

            return lines;
        }

        private static byte[] BuildSimplePdf(
            IReadOnlyList<
                List<string>
            > pages
        )
        {
            using var stream =
                new MemoryStream();

            var offsets =
                new List<long>
                {
                    0
                };

            void WriteAscii(
                string text
            )
            {
                var bytes =
                    Encoding.ASCII
                        .GetBytes(
                            text
                        );

                stream.Write(
                    bytes,
                    0,
                    bytes.Length
                );
            }

            WriteAscii(
                "%PDF-1.4\n"
            );

            var objectCount =
                3 +
                pages.Count * 2;

            var pageObjectIds =
                new List<int>();

            for (
                var i = 0;
                i <
                    pages.Count;
                i++
            )
            {
                pageObjectIds.Add(
                    4 + i * 2
                );
            }

            var objects =
                new Dictionary<
                    int,
                    string
                >();

            objects[1] =
                "<< /Type /Catalog /Pages 2 0 R >>";

            objects[2] =
                $"<< /Type /Pages /Kids [{string.Join(" ", pageObjectIds.Select(id => $"{id} 0 R"))}] /Count {pages.Count} >>";

            objects[3] =
                "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";

            for (
                var i = 0;
                i <
                    pages.Count;
                i++
            )
            {
                var pageId =
                    4 + i * 2;

                var contentId =
                    pageId + 1;

                var content =
                    BuildPdfPageContent(
                        pages[i]
                    );

                var contentLength =
                    Encoding.ASCII
                        .GetByteCount(
                            content
                        );

                objects[pageId] =
                    $"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents {contentId} 0 R >>";

                objects[contentId] =
                    $"<< /Length {contentLength} >>\nstream\n{content}\nendstream";
            }

            for (
                var id = 1;
                id <= objectCount;
                id++
            )
            {
                offsets.Add(
                    stream.Position
                );

                WriteAscii(
                    $"{id} 0 obj\n{objects[id]}\nendobj\n"
                );
            }

            var xrefOffset =
                stream.Position;

            WriteAscii(
                $"xref\n0 {objectCount + 1}\n"
            );

            WriteAscii(
                "0000000000 65535 f \n"
            );

            for (
                var id = 1;
                id <= objectCount;
                id++
            )
            {
                WriteAscii(
                    $"{offsets[id]:D10} 00000 n \n"
                );
            }

            WriteAscii(
                $"trailer\n<< /Size {objectCount + 1} /Root 1 0 R >>\nstartxref\n{xrefOffset}\n%%EOF"
            );

            return stream.ToArray();
        }

        private static string
            BuildPdfPageContent(
                IReadOnlyList<string>
                    lines
            )
        {
            var builder =
                new StringBuilder();

            builder.AppendLine(
                "BT"
            );

            builder.AppendLine(
                "/F1 9 Tf"
            );

            builder.AppendLine(
                "40 750 Td"
            );

            builder.AppendLine(
                "14 TL"
            );

            foreach (
                var line in
                    lines
            )
            {
                builder.Append(
                    "("
                );

                builder.Append(
                    EscapePdfText(
                        ToAscii(
                            line
                        )
                    )
                );

                builder.AppendLine(
                    ") Tj"
                );

                builder.AppendLine(
                    "T*"
                );
            }

            builder.Append(
                "ET"
            );

            return builder.ToString();
        }

        private static IEnumerable<string>
            WrapText(
                string value,
                int maxLength
            )
        {
            if (
                string.IsNullOrEmpty(
                    value
                )
            )
            {
                yield return
                    string.Empty;

                yield break;
            }

            var remaining =
                value.Trim();

            while (
                remaining.Length >
                    maxLength
            )
            {
                var split =
                    remaining.LastIndexOf(
                        ' ',
                        maxLength
                    );

                if (
                    split <= 0
                )
                {
                    split =
                        maxLength;
                }

                yield return
                    remaining[
                        ..split
                    ];

                remaining =
                    remaining[
                        split..
                    ]
                    .Trim();
            }

            yield return
                remaining;
        }

