                kpis.ActiveNurses
            );

            AppendCsvRow(
                builder,
                "Active proxies",
                kpis.ActiveProxies
            );

            AppendCsvRow(
                builder,
                "Appointments today",
                kpis.AppointmentsToday
            );

            AppendCsvRow(
                builder,
                "Pending appointments",
                kpis.PendingAppointments
            );

            AppendCsvRow(
                builder,
                "Collections due today",
                kpis.CollectionsDueToday
            );

            AppendCsvRow(
                builder,
                "Overdue collections",
                kpis.OverdueCollections
            );

            AppendCsvRow(
                builder,
                "Low stock items",
                kpis.LowStockItems
            );

            AppendCsvRow(
                builder,
                "Collected this month",
                kpis.CollectedThisMonth
            );

            AppendCsvRow(
                builder,
