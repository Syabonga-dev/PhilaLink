            AppendCsvRow(
                builder,
                "NEW PATIENTS"
            );

            AppendCsvRow(
                builder,
                "Full Name",
                "Patient Number",
                "Phone",
                "Registered"
            );

            foreach (
                var item in
                    report.NewPatients
            )
            {
                AppendCsvRow(
                    builder,
                    item.FullName,
                    item.PatientNumber,
                    item.PhoneNumber,
                    FormatDateTime(
                        item.CreatedAt
                    )
                );
            }

            /*
             * UTF-8 BOM makes Excel recognise the CSV encoding
             * reliably when opened directly.
             */
            var preamble =
                Encoding.UTF8
                    .GetPreamble();

            var body =
                Encoding.UTF8
                    .GetBytes(
                        builder.ToString()
                    );

            var result =
                new byte[
                    preamble.Length +
                    body.Length
                ];

            Buffer.BlockCopy(
                preamble,
                0,
                result,
                0,
                preamble.Length
            );

            Buffer.BlockCopy(
                body,
                0,
                result,
                preamble.Length,
                body.Length
            );

            return result;
        }

