                            item.CollectedAt.Value
                        ),
                    item.PatientName,
                    item.Status,
                    item.ProxyName,
                    item.ProcessedByNurseName,
                    item.TotalQuantity
                );
            }

            builder.AppendLine();

            AppendCsvRow(
                builder,
                "INVENTORY"
            );

            AppendCsvRow(
                builder,
                "Medication",
                "Strength",
                "Form",
                "Unit",
                "Quantity",
                "Reorder Level",
                "Status",
                "Active"
            );

            foreach (
                var item in
                    report.Inventory
            )
            {
                AppendCsvRow(
                    builder,
                    item.MedicationName,
                    item.Strength,
                    item.Form,
                    item.Unit,
                    item.QuantityOnHand,
                    item.ReorderLevel,
                    item.Status,
                    item.IsActive
                        ? "Yes"
