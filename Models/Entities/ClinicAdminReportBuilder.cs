        private static string BuildWorksheet(
            IReadOnlyList<
                List<object?>
            > rows
        )
        {
            var builder =
                new StringBuilder();

            builder.Append(
                """
                <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
                <worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
                  <sheetData>
                """
            );

            for (
                var rowIndex = 0;
                rowIndex <
                    rows.Count;
                rowIndex++
            )
            {
                var excelRow =
                    rowIndex + 1;

                builder.Append(
                    $"<row r=\"{excelRow}\">"
                );

                var row =
                    rows[rowIndex];

                for (
                    var columnIndex = 0;
                    columnIndex <
                        row.Count;
                    columnIndex++
                )
                {
                    var reference =
                        $"{ColumnName(columnIndex + 1)}{excelRow}";

                    AppendExcelCell(
                        builder,
                        reference,
                        row[columnIndex]
                    );
                }

                builder.Append(
                    "</row>"
                );
            }

            builder.Append(
                """
                  </sheetData>
                </worksheet>
                """
            );

            return builder.ToString();
        }

        private static void AppendExcelCell(
            StringBuilder builder,
            string reference,
            object? value
        )
        {
            if (value == null)
            {
                builder.Append(
                    $"<c r=\"{reference}\"/>"
                );

                return;
            }

            switch (value)
            {
                case byte number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                case short number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                case int number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                case long number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                case float number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                case double number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                case decimal number:
                    AppendNumberCell(
                        builder,
                        reference,
                        number
                    );
                    break;

                default:
                    builder.Append(
                        $"<c r=\"{reference}\" t=\"inlineStr\"><is><t>{XmlEscape(FormatValue(value))}</t></is></c>"
                    );
                    break;
            }
        }

        private static void AppendNumberCell(
            StringBuilder builder,
            string reference,
            object number
        )
        {
            builder.Append(
                $"<c r=\"{reference}\"><v>{Convert.ToString(number, CultureInfo.InvariantCulture)}</v></c>"
            );
        }

        private static string ColumnName(
            int column
        )
        {
            var result =
                string.Empty;

            while (
                column > 0
            )
            {
                column--;

                result =
                    (char)(
                        'A' +
                        column % 26
                    ) +
                    result;

                column /= 26;
            }

            return result;
        }

        private static void WriteZipEntry(
            ZipArchive archive,
            string path,
            string content
        )
        {
            var entry =
                archive.CreateEntry(
                    path,
                    CompressionLevel.Fastest
                );

            using var stream =
                entry.Open();

            using var writer =
                new StreamWriter(
                    stream,
                    new UTF8Encoding(
                        false
                    )
                );

            writer.Write(
                content
            );
        }

