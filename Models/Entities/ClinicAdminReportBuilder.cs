        public static byte[] BuildXlsx(
            ClinicAdminReportDataDto report
        )
        {
            var sheets =
                new List<
                    (
                        string Name,
                        List<List<object?>> Rows
                    )
                >
                {
                    (
                        "Summary",
                        BuildSummaryRows(
                            report
                        )
                    ),

                    (
                        "Appointments",
                        BuildAppointmentRows(
                            report
                        )
                    ),

                    (
                        "Collections",
                        BuildCollectionRows(
                            report
                        )
                    ),

                    (
                        "Inventory",
                        BuildInventoryRows(
                            report
                        )
                    ),

                    (
                        "Staff",
                        BuildStaffRows(
                            report
                        )
                    ),

                    (
                        "New Patients",
                        BuildPatientRows(
                            report
                        )
                    )
                };

            using var memory =
                new MemoryStream();

            using (
                var archive =
                    new ZipArchive(
                        memory,
                        ZipArchiveMode.Create,
                        true
                    )
            )
            {
                WriteZipEntry(
                    archive,
                    "[Content_Types].xml",
                    BuildContentTypes(
                        sheets.Count
                    )
                );

                WriteZipEntry(
                    archive,
                    "_rels/.rels",
                    """
                    <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
                    <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
                      <Relationship
                        Id="rId1"
                        Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument"
                        Target="xl/workbook.xml"/>
                    </Relationships>
                    """
                );

                WriteZipEntry(
                    archive,
                    "xl/workbook.xml",
                    BuildWorkbook(
                        sheets
                    )
                );

                WriteZipEntry(
                    archive,
                    "xl/_rels/workbook.xml.rels",
                    BuildWorkbookRelationships(
                        sheets.Count
                    )
                );

                WriteZipEntry(
                    archive,
                    "xl/styles.xml",
                    BuildStyles()
                );

                for (
                    var index = 0;
                    index <
                        sheets.Count;
                    index++
                )
                {
                    WriteZipEntry(
                        archive,
                        $"xl/worksheets/sheet{index + 1}.xml",
                        BuildWorksheet(
                            sheets[index]
                                .Rows
                        )
                    );
                }
            }

            return memory.ToArray();
        }

