            }

            builder.AppendLine();

            AppendCsvRow(
                builder,
                "STAFF"
            );

            AppendCsvRow(
                builder,
                "Full Name",
                "Role",
                "ID Number",
                "Phone",
                "Email",
                "Active",
                "Created"
            );

            foreach (
                var item in
                    report.Staff
            )
            {
                AppendCsvRow(
                    builder,
                    item.FullName,
                    item.Role,
                    item.IdNumber,
                    item.PhoneNumber,
                    item.Email,
                    item.IsActive
