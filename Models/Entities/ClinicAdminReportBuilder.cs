        private static void AppendCsvRow(
            StringBuilder builder,
            params object?[] values
        )
        {
            builder.AppendLine(
                string.Join(
                    ",",
                    values.Select(
                        CsvEscape
                    )
                )
            );
        }

        private static string CsvEscape(
            object? value
        )
        {
            var text =
                FormatValue(
                    value
                );

            text =
                text.Replace(
                    "\"",
                    "\"\""
                );

            return
                $"\"{text}\"";
        }

        private static string FormatValue(
            object? value
        )
        {
            return value switch
            {
                null =>
                    string.Empty,

                DateTime date =>
                    FormatDateTime(
                        date
                    ),

                bool boolean =>
                    boolean
                        ? "Yes"
                        : "No",

                IFormattable formattable =>
                    formattable.ToString(
                        null,
                        CultureInfo
                            .InvariantCulture
                    ) ??
                    string.Empty,

                _ =>
                    value.ToString() ??
                    string.Empty
            };
        }

        private static string XmlEscape(
            string value
        )
        {
            return
                SecurityElement.Escape(
                    value
                ) ??
                string.Empty;
        }

        private static string EscapePdfText(
            string value
        )
        {
            return value
                .Replace(
                    "\\",
                    "\\\\"
                )
                .Replace(
                    "(",
                    "\\("
                )
                .Replace(
                    ")",
                    "\\)"
                );
        }

        private static string ToAscii(
            string value
        )
        {
            var builder =
                new StringBuilder(
                    value.Length
                );

            foreach (
                var character in
                    value
            )
            {
                builder.Append(
                    character <= 127
                        ? character
                        : '?'
                );
            }

            return builder.ToString();
        }

        private static string FormatDate(
            DateTime value
        )
        {
            return value.ToString(
                "yyyy-MM-dd",
                CultureInfo.InvariantCulture
            );
        }

        private static string FormatDateTime(
            DateTime value
        )
        {
            return value.ToString(
                "yyyy-MM-dd HH:mm",
                CultureInfo.InvariantCulture
            );
        }
